import { chromium } from '../../node_modules/@playwright/test/index.mjs';
import assert from 'node:assert/strict';
import { writeFile } from 'node:fs/promises';
import { pathToFileURL } from 'node:url';
import path from 'node:path';
const root=process.cwd(), output=path.join(root,'.runtime/review-packet-20261017');
const browser=await chromium.launch({executablePath:'/usr/bin/google-chrome',args:['--no-sandbox']});
const page=await browser.newPage({viewport:{width:1440,height:1000}});
const errors=[],network=[];
await page.route('**/*',route=>/^https?:/.test(route.request().url())?route.abort():route.continue());
page.on('pageerror',e=>errors.push(String(e)));
page.on('console',m=>{if(m.type()==='error')errors.push(m.text());});
page.on('request',r=>{if(/^https?:/.test(r.url()))network.push(r.url());});
try{
 await page.goto(pathToFileURL(path.join(root,'docs/review-packets/2026-10-17-v0.11.17/index.html')).href);
 await page.evaluate(()=>document.fonts.ready);
 assert.equal(await page.locator('article').count(),28);
 assert.equal(await page.locator('#count').innerText(),'28 / 28 项');
 await page.screenshot({path:path.join(output,'overview.png')});
 await page.locator('#kind').selectOption('self_check');
 assert.equal(await page.locator('article:visible').count(),2);
 assert(await page.locator('article:visible img').evaluateAll(images=>images.every(i=>i.complete&&i.naturalWidth>0)));
 await page.screenshot({path:path.join(output,'illustrations.png'),fullPage:true});
 const cdp=await page.context().newCDPSession(page);
 await cdp.send('DOM.enable');await cdp.send('CSS.enable');
 const {root:documentRoot}=await cdp.send('DOM.getDocument');
 const {nodeId}=await cdp.send('DOM.querySelector',{nodeId:documentRoot.nodeId,selector:'h1'});
 const {fonts}=await cdp.send('CSS.getPlatformFontsForNode',{nodeId});
 assert(fonts.some(f=>f.isCustomFont&&f.postScriptName==='NotoSansCJKsc-Regular'&&f.glyphCount>0));
 await cdp.detach();
 await page.locator('#kind').selectOption('');
 await page.locator('#search').fill('不存在的审阅条目_xyz');
 assert.equal(await page.locator('article:visible').count(),0);
 assert(await page.locator('#empty').isVisible());
 await page.locator('#search').fill('risk.severe_breathing');
 assert.equal(await page.locator('article:visible').count(),1);
 await page.locator('article:visible summary').click();
 assert(await page.locator('article:visible pre').isVisible());
 await page.locator('#search').fill('');
 await page.locator('#kind').selectOption('self_check');
 await page.setViewportSize({width:390,height:844});
 assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
 await page.screenshot({path:path.join(output,'mobile.png'),fullPage:true});
 assert.deepEqual(errors,[]);assert.deepEqual(network,[]);
 const report={passed:true,review_items:28,illustrated_tasks:2,offline_images_loaded:true,kind_search_and_empty_state:true,mobile_width:390,horizontal_overflow:false,actual_heading_fonts:fonts,renderer_errors:errors,external_requests:network,scope:'Local file rendering and filtering; no clinical review or participant study.'};
 await writeFile(path.join(output,'ui-verification.json'),JSON.stringify(report,null,2)+'\n');
 console.log(JSON.stringify(report));
}finally{await browser.close();}
